"""Markdown FinOps report writer."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from .detectors import DETECTOR_LABELS

PLAYBOOK = {
    "compute": "Check autoscaling minimums, idle or orphaned instances and shutdown schedules; rightsize.",
    "storage": "Review lifecycle and versioning rules; expire non-current object versions.",
    "database": "Compare instance class and provisioned IOPS changes with measured utilisation.",
    "networking": "Trace egress paths (NAT, cross-AZ, CDN cache misses) and the deploy that changed them.",
    "ai_ml": "Cap endpoint max replicas; add client retry budgets and rate limits.",
    "analytics": "Enforce partition filters and per-query cost guards; pause idle pools.",
}


def service_label(provider: str, service: str) -> str:
    """'AWS S3' but 'Azure OpenAI' rather than 'Azure Azure OpenAI'."""
    return service if service.startswith(provider) else f"{provider} {service}"


def usd(v: float) -> str:
    return f"${v:,.0f}"


def pct(v: float) -> str:
    return f"{100 * v:.0f}%"


def _table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def render_report(summary: dict, truth: pd.DataFrame, planned: pd.DataFrame) -> str:
    d = summary["data"]
    ens = summary["ensemble"]
    att = summary["attribution"]
    sav = summary["savings"]
    anomalies = summary["anomalies"]
    lines: list[str] = []
    add = lines.append

    add("# Cloud Cost Anomaly Radar: FinOps report")
    add("")
    add(f"_Period {d['start']} to {d['end']} ({d['days']} days). Generated by `python -m costradar run` "
        f"(seed {summary['seed']})._")
    add("")
    add("> **Data notice:** all billing data in this report is synthetic, produced by the seeded generator in "
        "`src/costradar/generator.py`. Anomalies were injected on purpose so the detectors can be scored. "
        "No real account, customer or invoice is represented.")
    add("")

    add("## Headline")
    add("")
    add(_table(
        ["Metric", "Value"],
        [
            ["Total spend analysed", usd(d["total_spend_usd"])],
            ["Average daily spend", usd(d["avg_daily_spend_usd"])],
            ["Scope", f"{d['providers']} providers, {d['accounts']} accounts, {d['services']} services, {d['series']} series"],
            ["Anomaly events flagged (ensemble)", ens["events_flagged"]],
            ["Ensemble precision / recall / F1", f"{ens['precision']:.2f} / {ens['recall']:.2f} / {ens['f1']:.2f}"],
            ["Root cause ranked first correctly", f"{att['top1_driver_correct']} of {att['detected_anomalies']} detected anomalies ({pct(att['top1_accuracy'])})"],
            ["Estimated excess spend, all flagged events", usd(sav["estimated_excess_usd_all_events"])],
            ["Estimated vs injected excess (matched events)", f"{usd(sav['estimated_excess_usd_matched_events'])} vs {usd(sav['injected_excess_usd_detected_anomalies'])} ({pct(sav['capture_ratio'])})"],
        ],
    ))
    add("")

    add("## Anomaly register")
    add("")
    add("Each row is one ensemble event (flagged days merged across gaps of at most one day). "
        "Excess is spend above the seasonal baseline on the flagged days.")
    add("")
    rows = []
    for a in anomalies:
        dr = a["driver"]
        if a["matched_truth"]:
            note = f"{a['matched_truth']} ({a['truth_type'].replace('_', ' ')})"
        elif a["planned_event"]:
            note = f"False positive: planned event {a['planned_event']}"
        else:
            note = "False positive"
        rows.append([
            a["event_id"], f"{a['start']} to {a['end']}" if a["start"] != a["end"] else a["start"],
            a["flagged_days"], a["pattern"], a["severity"], usd(a["excess_usd"]), usd(a["peak_excess_usd"]),
            f"{service_label(dr['provider'], dr['service'])} ({dr['account']})", pct(dr["share"]), note,
        ])
    add(_table(["Event", "Dates", "Days", "Pattern", "Severity", "Excess", "Peak day", "Top driver",
                "Driver share", "Label match"], rows))
    add("")

    add("## Root cause detail: largest events")
    add("")
    for a in sorted(anomalies, key=lambda x: x["excess_usd"], reverse=True)[:5]:
        dr = a["driver"]
        add(f"### {a['event_id']}: {service_label(dr['provider'], dr['service'])} in `{dr['account']}`")
        add("")
        add(f"{a['start']} to {a['end']}, {a['flagged_days']} flagged day(s), estimated excess "
            f"**{usd(a['excess_usd'])}** ({pct(a['excess_pct_of_baseline'])} above baseline on those days). "
            f"Strongest monitor on the peak day: {a['top_monitor']}.")
        add("")
        add(_table(
            ["Rank", "Provider", "Account", "Service", "Delta vs baseline", "Share of increase"],
            [[i + 1, c["provider"], c["account"], c["service"], usd(c["delta_usd"]), pct(c["share"])]
             for i, c in enumerate(a["attribution"]["contributors"][:3])],
        ))
        add("")
        prov = ", ".join(f"{r['name']} {usd(r['delta_usd'])}" for r in a["attribution"]["by_provider"])
        add(f"By provider: {prov}.")
        add("")
        add(f"Suggested first check ({dr['category']}): {PLAYBOOK.get(dr['category'], 'Review recent changes.')}")
        add("")

    add("## Detector performance")
    add("")
    add("Event-level scoring against the 12 injected anomalies with a +/-2 day tolerance. A predicted event is a "
        "true positive if it overlaps any labelled window widened by two days on each side.")
    add("")
    rows = []
    for name in ("rolling_mad", "seasonal_residual", "isolation_forest", "ensemble"):
        m = summary["detectors"][name]
        rows.append([DETECTOR_LABELS[name], f"{m['precision']:.2f}", f"{m['recall']:.2f}", f"{m['f1']:.2f}",
                     m["predicted_events"], m["false_positive_events"], m["flagged_days"]])
    add(_table(["Detector", "Precision", "Recall", "F1", "Events", "False-positive events", "Flagged days"], rows))
    add("")
    if "robustness" in summary:
        r = summary["robustness"]
        add(f"Robustness: mean F1 over generator seeds {', '.join(map(str, r['seeds']))} (same detector settings): "
            + ", ".join(f"{DETECTOR_LABELS[n]} {v:.2f}" for n, v in r["mean_f1"].items()) + ".")
        add("")

    add("## Misses and false positives")
    add("")
    missed = ens["missed_anomalies"]
    if missed:
        t = truth.set_index("anomaly_id")
        for mid in missed:
            row = t.loc[mid]
            add(f"- Missed {mid} ({row['type'].replace('_', ' ')}, {service_label(row['provider'], row['service'])} in "
                f"`{row['account']}`, {row['start_date']} to {row['end_date']}, injected {usd(row['injected_excess_usd'])}).")
    else:
        add("- No injected anomaly was missed.")
    fps = [a for a in anomalies if not a["matched_truth"]]
    for a in fps:
        why = f"overlaps planned event {a['planned_event']}" if a["planned_event"] else "no matching label"
        add(f"- False positive {a['event_id']} ({a['start']} to {a['end']}, {usd(a['excess_usd'])}): {why}.")
    if not fps:
        add("- No false-positive events.")
    add("")
    if len(planned):
        add("Planned (expected) events in the synthetic year, not labelled as anomalies:")
        add("")
        add(_table(["ID", "Dates", "Scope", "Uplift", "Description"],
                   [[p.event_id, f"{p.start_date} to {p.end_date}", f"{p.categories} in {p.account_kinds}",
                     f"+{p.uplift_pct:.0f}%", p.description] for p in planned.itertuples(index=False)]))
        add("")

    add("## Ground truth: injected anomalies")
    add("")
    detected = set(summary["detectors"]["ensemble"]["detected_anomalies"])
    add(_table(
        ["ID", "Type", "Provider", "Account", "Service", "Window", "Uplift", "Injected excess", "Detected"],
        [[r.anomaly_id, r.type.replace("_", " "), r.provider, r.account, r.service,
          f"{r.start_date} to {r.end_date}", f"+{r.magnitude_pct:.0f}%", usd(r.injected_excess_usd),
          "yes" if r.anomaly_id in detected else "no"] for r in truth.itertuples(index=False)],
    ))
    add("")
    add("## How the savings estimate works")
    add("")
    add("Excess for an event is the sum over its flagged days of max(actual - baseline, 0) on total spend. "
        "The baseline is causal (trailing 21-day median of de-seasonalised spend, times the weekday and "
        "month-end factors), so sustained issues are only counted while they are flagged. That makes the "
        "estimate conservative for level shifts and slow leaks, which the capture ratio above shows.")
    add("")
    return "\n".join(lines)


def write_report(summary: dict, truth: pd.DataFrame, planned: pd.DataFrame, path: Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_report(summary, truth, planned))
    return path
